/* npm run demo:build: the GitHub Pages demo, in dist/demo/. A static copy of the site with the real editor, where
   everything a visitor does (edits, photos, publish, sign-ups) stays in their own browser (demo/store.js).
     node scripts/build-demo.mjs                       for http://127.0.0.1:8790/ (npm run demo:serve)
     node scripts/build-demo.mjs --base /Clip_Website/ for https://<owner>.github.io/Clip_Website/
   - The pages are rendered from content/seed with the same code the Worker uses, with links like about.html.
   - The editor is public/editor with demo/api.js in place of editor/api.js, at editor.html.
   - Every page sits at the demo's root, so the site's /assets/... paths become assets/.... (No <base href>: it
     would break the drawings, <use href="#flask">.) Only 404.html, which GitHub Pages serves at any depth, uses
     the full --base prefix.
   The real site never serves any of this: dist/ isn't in public/, and nothing here changes public/. */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { DOC_IDS, VIEW_IDS, norm } from "../public/shared/model.js";
import { renderPage, renderNotFound } from "../public/shared/export.js";
import { buildFacts, factsScript } from "../public/shared/facts.js";
import { readSeedDocs, SEED_TIME } from "./lib/seed.mjs";
import { demoLink, pageFile } from "../demo/links.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, dflt) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : dflt; };
const BASE = arg("--base", "/");
const OUT = path.resolve(ROOT, arg("--out", "dist/demo"));
if (!/^\/([A-Za-z0-9._-]+\/)*$/.test(BASE)) throw new Error(`--base must look like / or /Name/, not ${BASE}`);
if (!OUT.startsWith(path.join(ROOT, "dist") + path.sep)) throw new Error("--out must be inside dist/");

const read = (f) => fs.readFileSync(f, "utf8");
const write = (rel, text) => { const f = path.join(OUT, rel); fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, text); };
const must = (text, a, b, where) => { if (!text.includes(a)) throw new Error(`${where}: expected to find ${a}`); return text.split(a).join(b); };

/* 1. The site's own files. */
fs.rmSync(OUT, { recursive: true, force: true });
for (const dir of ["assets", "fonts", "shared", "editor"]) fs.cpSync(path.join(ROOT, "public", dir), path.join(OUT, dir), { recursive: true });
fs.rmSync(path.join(OUT, "editor/index.html"));

/* 2. Paths: /assets/ and /fonts/ become relative to the demo's root; photos come from this browser's storage. */
const relative = (text) => text.split('"/assets/').join('"assets/').split('"/fonts/').join('"fonts/');
for (const rel of ["shared/render.js", "shared/export.js", "editor/editor.js"]) write(rel, relative(read(path.join(OUT, rel))));
write("shared/model.js", must(read(path.join(OUT, "shared/model.js")), '"/photos/" + str(id)', '(globalThis.clipDemoPhoto ? globalThis.clipDemoPhoto(str(id)) : "")', "model.js"));
write("fonts/fonts.css", must(read(path.join(OUT, "fonts/fonts.css")), "url(/fonts/", "url(", "fonts.css"));
for (const rel of ["shared/render.js", "shared/model.js", "editor/editor.js", "assets/site.js"]) {
  if (/["'(]\/(assets|fonts|photos|shared|editor)\//.test(read(path.join(OUT, rel)))) throw new Error(`${rel} still has an absolute path`);
}

/* 3. The demo's own files, the seed it starts from, and its API in place of the editor's. */
fs.mkdirSync(path.join(OUT, "demo"), { recursive: true });
for (const f of ["store.js", "site.js", "links.js", "demo.css"]) fs.copyFileSync(path.join(ROOT, "demo", f), path.join(OUT, "demo", f));
const C = {};
for (const { id, doc } of readSeedDocs()) C[id] = doc;
for (const id of DOC_IDS) if (!C[id] || JSON.stringify(norm(id, C[id])) !== JSON.stringify(C[id])) throw new Error(`seed ${id} isn't normalized`);
write("demo/seed.js", "/* The content the demo starts from: content/seed, normalized. Generated by scripts/build-demo.mjs. */\nexport const SEED = " + JSON.stringify({ ...C, at: SEED_TIME }) + ";\n");
fs.copyFileSync(path.join(ROOT, "demo/api.js"), path.join(OUT, "editor/api.js"));

/* 4. The pages. p goes in front of the site's own paths: "" on pages at the demo's root, BASE on 404.html. */
const head = (html, p) => {
  const out = must(html, '<meta charset="utf-8">', '<meta charset="utf-8">\n<meta name="robots" content="noindex, nofollow">', "head");
  return out.split('="/assets/').join(`="${p}assets/`).split('="/fonts/').join(`="${p}fonts/`).split('="/editor/').join(`="${p}editor/`);
};
const page = (html, p) => {
  let out = head(html, p);
  out = must(out, "</head>", `<link rel="stylesheet" href="${p}demo/demo.css">\n</head>`, "page");
  out = must(out, `<script type="module" src="${p}assets/site.js"></script>`,
    `<script type="module" src="${p}demo/site.js"></script>\n<script type="module" src="${p}assets/site.js"></script>`, "page");
  return out;
};
for (const id of VIEW_IDS) write(pageFile(id), page(renderPage(C, id, { link: demoLink }), ""));
const fromAnywhere = (href) => { const l = demoLink(href); return /^https:/.test(l) ? l : BASE + l; };
write("404.html", page(renderNotFound(C, { link: fromAnywhere }), BASE).split('src="assets/').join(`src="${BASE}assets/`));
write("assets/clip-facts.js", factsScript(buildFacts(C)));
write("editor.html", head(read(path.join(ROOT, "public/editor/index.html")), ""));

console.log(`Built the demo in ${path.relative(ROOT, OUT)} for ${BASE}`);
