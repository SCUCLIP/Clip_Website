/* npm run fonts:fetch: download the site's fonts once into public/fonts, so pages never load anything from Google.
   Caveat, DM Sans and DM Mono are under the SIL Open Font License 1.1; each family's OFL.txt is saved next to
   the font files. Only the latin and latin-ext subsets are kept. The result is committed; run this again only
   to change the fonts. */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "public", "fonts");
/* The same families and weights the original export loaded. */
const CSS_URL = "https://fonts.googleapis.com/css2?family=Caveat:wght@500;700&family=DM+Mono:wght@400;500&family=DM+Sans:opsz,wght@9..40,400;9..40,500;9..40,700&display=swap";
const LICENSES = {
  Caveat: "https://raw.githubusercontent.com/google/fonts/main/ofl/caveat/OFL.txt",
  "DM Mono": "https://raw.githubusercontent.com/google/fonts/main/ofl/dmmono/OFL.txt",
  "DM Sans": "https://raw.githubusercontent.com/google/fonts/main/ofl/dmsans/OFL.txt",
};
const SUBSETS = new Set(["latin", "latin-ext"]);
/* A current desktop browser's User-Agent, so Google serves woff2. */
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36";

async function get(url, type) {
  const res = await fetch(url, { headers: { "User-Agent": UA } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return type === "bytes" ? new Uint8Array(await res.arrayBuffer()) : res.text();
}

const css = await get(CSS_URL);
const blocks = [...css.matchAll(/\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g)];
if (!blocks.length) throw new Error("Google Fonts returned no @font-face rules");
fs.mkdirSync(out, { recursive: true });
for (const f of fs.readdirSync(out)) if (/\.(woff2|css|txt)$/.test(f)) fs.rmSync(path.join(out, f));

const files = new Map();
const faces = [];
for (const [, subset, block] of blocks) {
  if (!SUBSETS.has(subset)) continue;
  const family = /font-family:\s*'([^']+)'/.exec(block)[1];
  const url = /src:\s*url\(([^)]+)\)/.exec(block)[1];
  if (!files.has(url)) {
    const slug = family.toLowerCase().replace(/\s+/g, "-");
    let name = `${slug}-${subset}.woff2`, n = 2;
    while ([...files.values()].includes(name)) name = `${slug}-${subset}-${n++}.woff2`;
    files.set(url, name);
    fs.writeFileSync(path.join(out, name), await get(url, "bytes"));
  }
  faces.push(`/* ${family}, ${subset} */\n` + block.replace(/src:\s*url\([^)]+\)/, `src: url(/fonts/${files.get(url)})`));
}
fs.writeFileSync(path.join(out, "fonts.css"),
  "/* Caveat, DM Mono and DM Sans, self-hosted. SIL Open Font License 1.1: see OFL-*.txt in this folder.\n" +
  "   Generated by `npm run fonts:fetch`. */\n" + faces.join("\n") + "\n");
for (const [family, url] of Object.entries(LICENSES)) {
  fs.writeFileSync(path.join(out, `OFL-${family.replace(/\s+/g, "")}.txt`), await get(url));
}
console.log(`Saved ${files.size} font files, fonts.css and ${Object.keys(LICENSES).length} licenses to public/fonts.`);
